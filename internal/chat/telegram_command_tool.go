package chat

import (
	"context"
	"encoding/json"
	"fmt"
	"io"
	"strings"

	"goaster/internal/telegramcommands"
)

var telegramCommandReferenceCodexTool = codexTool{
	Type:        "function",
	Name:        telegramcommands.CommandReferenceToolName,
	Description: "Read the current Telegram command catalog compiled into this running GoAster binary. This read-only tool takes no arguments and does not read or write installed files; use it for Telegram command usage, aliases, behavior, and access requirements.",
	Parameters: map[string]any{
		"type":                 "object",
		"properties":           map[string]any{},
		"additionalProperties": false,
	},
}

// executeTelegramCommandReference renders the catalog at invocation time so
// an upgraded binary cannot inherit a reference generated by an older install.
func executeTelegramCommandReference(ctx context.Context, arguments string) (string, error) {
	if err := ctx.Err(); err != nil {
		return "", err
	}
	if err := parseTelegramCommandReferenceArguments(arguments); err != nil {
		return "", err
	}
	if err := ctx.Err(); err != nil {
		return "", err
	}
	return telegramcommands.Reference(), nil
}

func parseTelegramCommandReferenceArguments(arguments string) error {
	decoder := json.NewDecoder(strings.NewReader(arguments))
	var args map[string]json.RawMessage
	if err := decoder.Decode(&args); err != nil {
		return fmt.Errorf("%s arguments are not valid JSON: %w", telegramCommandReferenceCodexTool.Name, err)
	}
	if args == nil {
		return fmt.Errorf("%s arguments must be an empty JSON object", telegramCommandReferenceCodexTool.Name)
	}
	var extra json.RawMessage
	if err := decoder.Decode(&extra); err == nil {
		return fmt.Errorf("%s arguments contain more than one JSON value", telegramCommandReferenceCodexTool.Name)
	} else if err != io.EOF {
		return fmt.Errorf("%s arguments are not valid JSON: %w", telegramCommandReferenceCodexTool.Name, err)
	}
	if len(args) != 0 {
		return fmt.Errorf("%s takes no arguments", telegramCommandReferenceCodexTool.Name)
	}
	return nil
}
